export function testPattern5GPy(pattern, size, square, matlabGray) {
  const hSize = size === "input" ? null : Number(size);
  const name = pattern;
  const radius = Math.max(1, Math.floor(square / 4));
  const colors = "[[255,255,255],[0,255,255],[255,255,0],[0,255,0],[255,0,255],[0,0,255],[255,0,0],[0,0,0]]";
  const make = pattern === "color_bars"
    ? [`    bars = np.asarray(${colors}, dtype=np.uint8)`, "    img = bars[(8 * xx // w)]"]
    : pattern === "checkerboard"
      ? [`    bright = (((xx // ${square}) + (yy // ${square})) & 1) == 1`, `    img = np.where(bright & (xx >= w // 2), 179, np.where(bright, 255, 0)).astype(np.uint8) if ${matlabGray ? "True" : "False"} else (bright.astype(np.uint8) * 255)`]
      : pattern === "grid"
        ? [`    img = np.full((h, w), 255, dtype=np.uint8)`, `    img[(xx % ${square} == 0) | (yy % ${square} == 0) | (xx == w - 1) | (yy == h - 1)] = 0`]
        : pattern === "dots"
          ? [`    dx = xx - (xx // ${square}) * ${square} - ${square} // 2`, `    dy = yy - (yy // ${square}) * ${square} - ${square} // 2`, `    img = (((dx * dx) + (dy * dy)) <= ${radius * radius}).astype(np.uint8) * 255`]
          : pattern === "ramp_h"
            ? ["    img = np.zeros((h, w), dtype=np.uint8) if w == 1 else ((510 * xx + w - 1) // (2 * (w - 1))).astype(np.uint8)"]
            : ["    img = np.zeros((h, w), dtype=np.uint8) if h == 1 else ((510 * yy + h - 1) // (2 * (h - 1))).astype(np.uint8)"];
  return [
    `if ${hSize === null ? "True" : "False"} and img.size == 0:`,
    "    img = img.copy()",
    "    print('ภาพว่าง')",
    "else:",
    ...(hSize === null ? ["    h, w = img.shape[:2]"] : [`    h, w = ${hSize}, ${hSize}`]),
    `    yy, xx = np.indices((h, w), dtype=np.int64)`,
    ...make,
    `    print(f\"Test pattern ${pattern === "color_bars" ? "แถบสี 8 สี" : name} {w}×{h}\")`,
  ];
}

