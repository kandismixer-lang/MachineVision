    "    sim5g_xn = np.floor(sim5g_sx + 0.5).astype(np.int64)",
    "    sim5g_yn = np.floor(sim5g_sy + 0.5).astype(np.int64)",
    "    sim5g_valid = (sim5g_xn >= 0) & (sim5g_xn < sim5g_w) & (sim5g_yn >= 0) & (sim5g_yn < sim5g_h)",
    "    sim5g_out = np.zeros((sim5g_out_h, sim5g_out_w, sim5g_ch), dtype=np.uint8)",
    "    sim5g_out[sim5g_valid] = sim5g_src[sim5g_yn[sim5g_valid], sim5g_xn[sim5g_valid]]",
