    "                fir5g_im += fir5g_ii * fir5g_C[fir5g_a] - fir5g_rr * fir5g_S[fir5g_a]",
    "            fir5g_mag[fir5g_g2, fir5g_g1] = math.sqrt(fir5g_re * fir5g_re + fir5g_im * fir5g_im)",
    "    fir5g_scale = max(1.0, float(np.max(fir5g_mag)))",
    "    fir5g_img = np.zeros((256, 256), np.uint8)",
    "    for fir5g_y in range(256):",
    "        fir5g_g2 = 63 - fir5g_y // 4",
    "        for fir5g_x in range(256):",
    "            fir5g_g1 = fir5g_x // 4",
    "            fir5g_img[fir5g_y, fir5g_x] = min(255, int(math.floor(fir5g_mag[fir5g_g2, fir5g_g1] / fir5g_scale * 255 + 0.5)))",
    "    img = fir5g_img",
    "else:",
    "    fir5g_q = max(1, 256 // fir5g_n); fir5g_side = fir5g_n * fir5g_q",
    "    fir5g_maxabs = float(np.max(np.abs(fir5g_kernel)))",
