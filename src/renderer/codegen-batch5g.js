    "                sc5g_cur = sc5g_d[:, sc5g_x]",
    "                sc5g_new = np.minimum(sc5g_cur, sc5g_d[:, sc5g_x + 1] + sc5g_eh[:, sc5g_x])",
    "                sc5g_new[1:] = np.minimum(sc5g_new[1:], sc5g_d[:-1, sc5g_x + 1] + sc5g_ea[:, sc5g_x])",
    "                sc5g_new[:-1] = np.minimum(sc5g_new[:-1], sc5g_d[1:, sc5g_x + 1] + sc5g_ed[:, sc5g_x])",
    "                if np.any(sc5g_new < sc5g_cur): sc5g_changed = True",
    "                sc5g_d[:, sc5g_x] = sc5g_new",
    "            for sc5g_y in range(1, sc5g_h):",
    "                sc5g_cur = sc5g_d[sc5g_y, :]",
    "                sc5g_new = np.minimum(sc5g_cur, sc5g_d[sc5g_y - 1, :] + sc5g_ev[sc5g_y - 1, :])",
    "                sc5g_new[1:] = np.minimum(sc5g_new[1:], sc5g_d[sc5g_y - 1, :-1] + sc5g_ed[sc5g_y - 1, :])",
    "                sc5g_new[:-1] = np.minimum(sc5g_new[:-1], sc5g_d[sc5g_y - 1, 1:] + sc5g_ea[sc5g_y - 1, :])",
    "                if np.any(sc5g_new < sc5g_cur): sc5g_changed = True",
    "                sc5g_d[sc5g_y, :] = sc5g_new",
    "            for sc5g_y in range(sc5g_h - 2, -1, -1):",
    "                sc5g_cur = sc5g_d[sc5g_y, :]",
    "                sc5g_new = np.minimum(sc5g_cur, sc5g_d[sc5g_y + 1, :] + sc5g_ev[sc5g_y, :])",
    "                sc5g_new[1:] = np.minimum(sc5g_new[1:], sc5g_d[sc5g_y + 1, :-1] + sc5g_ea[sc5g_y, :])",
    "                sc5g_new[:-1] = np.minimum(sc5g_new[:-1], sc5g_d[sc5g_y + 1, 1:] + sc5g_ed[sc5g_y, :])",
    "                if np.any(sc5g_new < sc5g_cur): sc5g_changed = True",
    "                sc5g_d[sc5g_y, :] = sc5g_new",
    "            sc5g_sets += 1",
    "            if not sc5g_changed: sc5g_stable = True; break",
    "        return sc5g_d, sc5g_sets, sc5g_stable",
    "    sc5g_dr, sc5g_sr, sc5g_cr = sc5g_sweep(sc5g_lab == 1)",
    "    sc5g_db, sc5g_sb, sc5g_cb = sc5g_sweep(sc5g_lab == 2)",
    "    sc5g_obj = sc5g_dr < sc5g_db",
    "    sc5g_area = int(np.count_nonzero(sc5g_obj))",
    "    sc5g_k = sc5g_sr + sc5g_sb",
    "    sc5g_converged = sc5g_cr and sc5g_cb",
    "    sc5g_finite = np.isfinite(sc5g_dr)",
    "    sc5g_maxd = float(np.max(sc5g_dr[sc5g_finite])) if np.any(sc5g_finite) else 0.0",
